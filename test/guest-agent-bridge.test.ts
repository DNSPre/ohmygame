import { afterEach, describe, expect, it, vi } from "vitest";
import { startGuestAgentBridge, type GuestAgentId } from "../src/daemon/guest-agent-bridge.js";

const bridges: Awaited<ReturnType<typeof startGuestAgentBridge>>[] = [];
afterEach(async () => { await Promise.all(bridges.splice(0).map(bridge => bridge.close())); });
async function fixture(generate = vi.fn(async () => "<html>Generated by fixture</html>")) {
  const discover = vi.fn(async (_id: GuestAgentId, _directory: string) => ({ installed: true, auth: "signed-in", models: [{ id: "account-model", name: "Account Model" }] }));
  const bridge = await startGuestAgentBridge({ port: 0, discover, generate });
  bridges.push(bridge);
  const url = "http://127.0.0.1:" + bridge.port;
  const headers = { Authorization: "Bearer " + bridge.token, Origin: "https://game.design.cab", "Content-Type": "application/json" };
  return { ...bridge, url, headers, discover, generate };
}
const body = JSON.stringify({ agent: "codex", model: "account-model", messages: [{ role: "user", content: "Create a browser game" }] });

describe("guest native agent connector", () => {
  it("refuses unauthenticated requests without browser login dialogs", async () => {
    const bridge = await fixture();
    const response = await fetch(bridge.url + "/agents/codex/models");
    expect(response.status).toBe(401);
    expect(response.headers.has("www-authenticate")).toBe(false);
    expect(bridge.discover).not.toHaveBeenCalled();
  });
  it("denies foreign origins even with the correct token", async () => {
    const bridge = await fixture();
    const response = await fetch(bridge.url + "/agents/codex/models", { headers: { ...bridge.headers, Origin: "https://unrelated.example" } });
    expect(response.status).toBe(403);
    expect(bridge.discover).not.toHaveBeenCalled();
  });
  it("permits preflight from the game site without credentials", async () => {
    const bridge = await fixture();
    const response = await fetch(bridge.url + "/agents/codex/models", { method: "OPTIONS", headers: { Origin: "https://game.design.cab" } });
    expect(response.status).toBe(204);
    expect(response.headers.get("access-control-allow-origin")).toBe("https://game.design.cab");
    expect(response.headers.get("access-control-allow-private-network")).toBe("true");
  });
  it("returns the CLI catalog and caches repeated probes", async () => {
    const bridge = await fixture();
    const request = () => fetch(bridge.url + "/agents/claude-code/models", { headers: bridge.headers }).then(response => response.json());
    const [first, second] = await Promise.all([request(), request()]);
    expect(first.models[0].id).toBe("account-model");
    expect(second).toEqual(first);
    expect(bridge.discover).toHaveBeenCalledTimes(1);
    expect(bridge.discover.mock.calls[0]?.[0]).toBe("claude-code");
  });
  it("passes only validated generation requests to the selected CLI", async () => {
    const bridge = await fixture();
    const response = await fetch(bridge.url + "/agents/generate", { method: "POST", headers: bridge.headers, body });
    expect(response.status).toBe(200);
    expect((await response.json()).content).toContain("Generated by fixture");
    expect(bridge.generate.mock.calls[0]?.slice(0, 3)).toEqual(["codex", "account-model", [{role:"user",content:"Create a browser game"}]]);
  });
  it("does not accept arbitrary executable names or commands", async () => {
    const bridge = await fixture();
    const response = await fetch(bridge.url + "/agents/generate", { method: "POST", headers: bridge.headers, body: JSON.stringify({ agent: "bash", model: "x", messages: [{role:"user",content:"echo test"}] }) });
    expect(response.status).toBe(400);
    expect(bridge.generate).not.toHaveBeenCalled();
    expect((await fetch(bridge.url + "/exec", { method: "POST", headers: bridge.headers, body: "{}" })).status).toBe(404);
  });
});
